    private void CreateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CreateButtonActionPerformed
        List<String> errors = new ArrayList<>();

        String customerName = jTextField1.getText().trim();
        String carPlate = jTextField2.getText().trim().toUpperCase();
        String serviceType = String.valueOf(jComboBox1.getSelectedItem());
        String datetime = jTextField3.getText().trim();
        String technician = jTextField4.getText().trim();
        String comment = jTextArea1.getText().trim();

        FileUtil.loadPrices();
        ServicePrice servicePrice = FileUtil.findPriceByServiceType(serviceType);
        if (servicePrice == null) {
            errors.add("No price is set in price.txt for service type '" + serviceType + "'. Ask the manager to set the price first.");
        }

        if (customerName.isEmpty()) {
            errors.add("Customer name is required.");
        } else if (customerName.length() > 60) {
            errors.add("Customer name must be 60 characters or fewer.");
        } else if (customerName.contains("|")) {
            errors.add("Customer name cannot contain the '|' character.");
        } else if (!customerExists(customerName)) {
            errors.add("Customer '" + customerName + "' is not a valid customer username in users.txt.");
        }

        if (!carPlate.matches("[A-Z0-9]{2,10}")) {
            errors.add("Carplate must be 2-10 letters/numbers with no spaces or symbols.");
        }

        try {
            LocalDateTime dt = LocalDateTime.parse(datetime);
            if (dt.isBefore(LocalDateTime.now())) {
                errors.add("Datetime cannot be in the past.");
            }
            if (dt.getHour() < 6) {
                errors.add("Appointment time is too early, must between 06:00 to 22:00");
            }
            if (dt.getHour() >= 22) {
                errors.add("Appointment time is too early, must between 06:00 to 22:00");
            }
        } catch (DateTimeParseException e) {
            errors.add("Datetime must use ISO format: yyyy-MM-dd'T'HH:mm (e.g. 2026-10-25T09:30).");
        }

        if (technician.isEmpty()) {
            errors.add("Technician is required.");
        } else if (!technicianExists(technician)) {
            errors.add("Technician '" + technician + "' is not a valid technician username in users.txt.");
        }

        if (comment.contains("|")) {
            errors.add("Customer comment cannot contain the '|' character.");
        } else if (comment.length() > 200) {
            errors.add("Customer comment must be 200 characters or fewer.");
        }
        
        try {
            LocalDateTime newDT = LocalDateTime.parse(datetime);
            for (Appointment apt : FileUtil.allAppointments){
                if (apt.getTechnician().equals(technician)){
                    LocalDateTime bookedDT = LocalDateTime.parse(apt.getDatetime());
                    long minsBetween = Duration.between(newDT, bookedDT).abs().toMinutes();
                    if (minsBetween < 180) {
                        errors.add("This timeslot is already booked, find another technician or time");
                    }
                }
            }
        } catch (DateTimeParseException e) {
            //no need to add error again cuz earlier already add once
        }

        if (!errors.isEmpty()) {
            JOptionPane.showMessageDialog(this, String.join("\n", errors), "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        
        Appointment apt = new Appointment(customerName, carPlate, serviceType, datetime, technician, comment);
        createdAppointment = apt;
        JOptionPane.showMessageDialog(this, "Appointment " + apt.getAppointmentId() + " created.", "Success", JOptionPane.INFORMATION_MESSAGE);
        this.dispose();
    }//GEN-LAST:event_CreateButtonActionPerformed

    private boolean customerExists(String customerName) {
        FileUtil.loadAllUsers();
        for (User u : FileUtil.allUsers) {
            if (u.getUsername().equalsIgnoreCase(customerName)) {
                return u.getRole().equalsIgnoreCase("Customer");
            }
        }
        return false;
    }

    private boolean technicianExists(String technician) {
        FileUtil.loadAllUsers();
        for (User u : FileUtil.allUsers) {
            if (u.getUsername().equalsIgnoreCase(technician)) {
                return u.getRole().equalsIgnoreCase("Technician");
            }
        }
        return false;
    }

