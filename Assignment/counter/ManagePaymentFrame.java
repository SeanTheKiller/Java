    private void CollectPaymentButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CollectPaymentButtonActionPerformed
        // TODO add your handling code here:
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            return;
        }

        String status = jTable1.getValueAt(row, 3).toString();

        if (!"Completed".equalsIgnoreCase(status)) {
            JOptionPane.showMessageDialog(this,
                    "Only completed appointments can collect payment.",
                    "Action Denied", JOptionPane.ERROR_MESSAGE);
            return;
        }

        double billed = ((Number) jTable1.getValueAt(row, 4)).doubleValue();
        double paid = ((Number) jTable1.getValueAt(row, 5)).doubleValue();

        if (paid >= billed) {
            JOptionPane.showMessageDialog(this,
                    "Payment already fully collected for this appointment.",
                    "Action Denied", JOptionPane.ERROR_MESSAGE);
            return;
        }

        showCollectPaymentDialog(row, billed, paid);
    }//GEN-LAST:event_CollectPaymentButtonActionPerformed

