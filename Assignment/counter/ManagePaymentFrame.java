    private void showReceiptDialog(int row) {
        String appointmentId = jTable1.getValueAt(row, 0).toString();
        Appointment apt = FileUtil.findAppointmentByID(appointmentId);
        String generatedAt = java.time.LocalDateTime.now()
                .format(java.time.format.DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"));

        java.util.List<String> lines = new java.util.ArrayList<>();
        lines.add("=============== SERVICE RECEIPT ===============");
        lines.add("Receipt No : R-" + appointmentId);
        lines.add("Generated  : " + generatedAt);
        lines.add("-----------------------------------------------");
        lines.add("Appointment ID : " + appointmentId);
        lines.add("Customer Name  : " + apt.getCustomerName());
        lines.add("Car Plate      : " + apt.getCarPlate());
        lines.add("Service Type   : " + apt.getServiceType());
        lines.add("Datetime       : " + apt.getDatetime());
        lines.add("Technician     : " + apt.getTechnician());
        lines.add("Service Status : " + apt.getStatus());
        lines.add("-----------------------------------------------");
        lines.add("Billed Amount  : RM " + String.format("%.2f", jTable1.getValueAt(row, 4)));
        lines.add("Paid Amount    : RM " + String.format("%.2f", jTable1.getValueAt(row, 5)));
        lines.add("Status         : FULLY PAID");
        lines.add("===============================================");
        lines.add("Thank you for choosing our service!");
        FileUtil.write("Receipt-" + appointmentId + ".txt", lines);

        JTextArea textArea = new JTextArea(String.join("\n", lines));
        textArea.setFont(new java.awt.Font("Monospaced", java.awt.Font.PLAIN, 14));
        textArea.setEditable(false);
        textArea.setCaretPosition(0);

        JDialog dialog = new JDialog(this, "Receipt - " + appointmentId, true);
        dialog.setLayout(new java.awt.BorderLayout(10, 10));
        dialog.add(new JScrollPane(textArea), java.awt.BorderLayout.CENTER);

        JButton okButton = new JButton("OK");
        okButton.addActionListener(e2 -> dialog.dispose());
        javax.swing.JPanel buttonPanel = new javax.swing.JPanel(new FlowLayout(FlowLayout.CENTER));
        buttonPanel.add(okButton);
        dialog.add(buttonPanel, java.awt.BorderLayout.SOUTH);

        dialog.setSize(550, 500);
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);
    }

